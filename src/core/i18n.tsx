const dictionaries: Record<Language, Record<TranslationKey, string>> = { fa, en };

export const LanguageContext = createContext<{ lang: Language }>({ lang: 'fa' });

export function LanguageProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  return <LanguageContext.Provider value={{ lang }}>{children}</LanguageContext.Provider>;
}

export function useT() {
  const { lang } = useContext(LanguageContext);
  return (key: TranslationKey): string => dictionaries[lang][key] ?? fa[key] ?? key;
}

export function useLang(): Language {
  return useContext(LanguageContext).lang;
}
